if __name__ == '__main__':
    # Integer variable
    integer_var = 10
    print("Integer:", integer_var, "| Type:", type(integer_var))

    # Floating-point variable
    float_var = 20.5
    print("Floating-point number:", float_var, "| Type:", type(float_var))

    # String variable
    string_var = "Learning Python"
    print("String:", string_var, "| Type:", type(string_var))

    # Boolean variable
    boolean_var = True
    print("Boolean:", boolean_var, "| Type:", type(boolean_var))

    # List variable (a collection of items)
    list_var = [1, 2, 3, 4, 5]
    print("List:", list_var, "| Type:", type(list_var))

    # Tuple variable (an immutable collection of items)
    tuple_var = (10, 20, 30)
    print("Tuple:", tuple_var, "| Type:", type(tuple_var))

    # Dictionary variable (key-value pairs)
    dict_var = {"name": "Alice", "age": 25}
    print("Dictionary:", dict_var, "| Type:", type(dict_var))

    # Set variable (unique unordered collection)
    set_var = {1, 2, 3, 4, 5}
    print("Set:", set_var, "| Type:", type(set_var))

    # NoneType variable (represents the absence of a value)
    none_var = None
    print("NoneType:", none_var, "| Type:", type(none_var))

    
    # Declare and initialize an integer variable
    zahl = 10
    print("Integer variable 'zahl':", zahl, "| Type:", type(zahl))

    # Declare and initialize a floating-point variable
    kommazahl = 10.5
    print("Floating-point variable 'kommazahl':", kommazahl, "| Type:", type(kommazahl))

    # Declare and initialize a string variable
    text = "Hello, World!"
    print("String variable 'text':", text, "| Type:", type(text))

    # Declare and initialize a boolean variable
    wahrheitswert = True
    print("Boolean variable 'wahrheitswert':", wahrheitswert, "| Type:", type(wahrheitswert))

    abc = False
    print("Boolean variable abc :", abc, type(abc))
    # Output all variables together with descriptions
    print("\nSummary of all variables:")
    print(f"Integer 'zahl': {zahl}")
    print(f"Floating-point 'kommazahl': {kommazahl}")
    print(f"String 'text': {text}")
    print(f"Boolean 'wahrheitswert': {wahrheitswert}")
    print(f"abc: {abc}")